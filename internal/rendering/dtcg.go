// The four files ExportDesignTokens writes. The resolver names the other three by these paths, relative to itself.
const (
	DesignTokensBaseFile     = "base.tokens.json"
	DesignTokensLightFile    = "light.tokens.json"
	DesignTokensDarkFile     = "dark.tokens.json"
	DesignTokensResolverFile = "menata.resolver.json"
)

const (
	dtcgFormatSchema   = "https://www.designtokens.org/schemas/2025.10/format.json"
	dtcgResolverSchema = "https://www.designtokens.org/schemas/2025.10/resolver.json"
	dtcgExtension      = "app.menata" // the vendor key under $extensions (DTCG format §5.2.3)
)

// DesignTokenFiles is one Workspace's Theme as W3C DTCG 2025.10 documents (rencana 3.4).
//
// Mode-independent tokens (spacing, radius, typography) are in Base; colours are in Light and Dark, under the same
// names; Resolver is the 2025.10 Resolver Module document that puts them together (a `base` set, then a `mode` modifier
// whose contexts are `light` and `dark`, `light` by default). A tool that reads no resolver reads Base with one mode file.
type DesignTokenFiles struct {
	Base, Light, Dark, Resolver []byte
}

// ExportDesignTokens writes ws's Theme as DTCG tokens. appCSS is the compiled `static/css/app.css`: every value is what
// the browser computes for a page in ws -- app.css's own defaults and dark block, with themeCSS's override for ws
// applied over each mode -- so a token cannot say something a page does not draw. The names are the Design System
// artifact's (designTokenClasses), so a mockup's `var(--ink-body)` is the token `color.ink-body`.
//
// **What it does not carry:** the artifact's tokens no reader answers for (GS1's `dsUnmapped`); a type style's
// `uppercase`, which DTCG typography has no field for; and the touch half of `control-height-compact`. A colour that
// computes to a `color-mix` is evaluated (the free accent's hover), since DTCG has no mix.
func ExportDesignTokens(ws domain.Workspace, appCSS string) (DesignTokenFiles, error) {
	ctx := WithCurrentWorkspace(context.Background(), ws, ws.Slug, false)
	light, dark, err := appCSSModeVars(appCSS)
	if err != nil {
		return DesignTokenFiles{}, err
	}
	override := themeCSS(ctx)
	for k, v := range themeOverrideBlock(override, themeCSSLight) {
		light[k] = v
	}
	for k, v := range themeOverrideBlock(override, themeCSSDark) {
		dark[k] = v
	}

	m := designTokenClasses(ctx)
	who := "the default Theme"
	if ws.Slug != "" {
		who = "Workspace " + ws.Slug
	}
	colourDoc := func(vars map[string]string, mode string) (map[string]any, error) {
		group := map[string]any{"$type": "color"}
		for _, name := range sortedNames(m.colour) {
			class := m.colour[name]
			prop := "--color-" + class[strings.Index(class, "-")+1:]
			c, err := resolveCSSColour(vars, prop)
			if err != nil {
				return nil, fmt.Errorf("color.%s (%s, %s): %w", name, class, mode, err)
			}
			group[name] = map[string]any{"$value": c.dtcg(), "$extensions": map[string]any{dtcgExtension: map[string]string{"class": class, "property": prop}}}
		}
		return map[string]any{
			"$schema":      dtcgFormatSchema,
			"$description": "Menata App colour tokens, " + mode + " mode, " + who + ". Generated by ExportDesignTokens; do not edit.",
			"color":        group,
		}, nil
	}
	lightDoc, err := colourDoc(light, "light")
	if err != nil {
		return DesignTokenFiles{}, err
	}
	darkDoc, err := colourDoc(dark, "dark")
	if err != nil {
		return DesignTokenFiles{}, err
	}

	spacing, radius := map[string]any{"$type": "dimension"}, map[string]any{"$type": "dimension"}
	for _, name := range sortedNames(m.length) {
		class := m.length[name]
		px, err := cssLengthPx(light, class)
		if err != nil {
			return DesignTokenFiles{}, fmt.Errorf("%s (%s): %w", name, class, err)
		}
		tok := map[string]any{"$value": dtcgPx(px), "$extensions": map[string]any{dtcgExtension: map[string]string{"class": class}}}
		if strings.HasPrefix(name, "radius-") {
			radius[name] = tok
		} else {
			spacing[name] = tok
		}
	}
	family, err := cssFontFamily(light["--font-sans"])
	if err != nil {
		return DesignTokenFiles{}, err
	}
	typography := map[string]any{"$type": "typography"}
	for _, name := range sortedNames(m.styles) {
		st := m.styles[name]
		size, lh, err := cssTextPx(light, st.size)
		if err != nil {
			return DesignTokenFiles{}, fmt.Errorf("typography.%s: %w", name, err)
		}
		weight, err := strconv.Atoi(light["--font-weight-"+strings.TrimPrefix(st.weight, "font-")])
		if err != nil {
			return DesignTokenFiles{}, fmt.Errorf("typography.%s: weight %s has no number in app.css", name, st.weight)
		}
		tracking := 0.0
		if st.tracking != "" {
			em, ok := strings.CutSuffix(light["--"+st.tracking], "em")
			f, err := strconv.ParseFloat(em, 64)
			if !ok || err != nil {
				return DesignTokenFiles{}, fmt.Errorf("typography.%s: %s is not an em value in app.css", name, st.tracking)
			}
			tracking = round(f*size, 4)
		}
		typography[name] = map[string]any{
			"$value": map[string]any{"fontFamily": family, "fontSize": dtcgPx(size), "fontWeight": weight,
				"letterSpacing": dtcgPx(tracking), "lineHeight": round(lh/size, 6)},
			"$extensions": map[string]any{dtcgExtension: map[string]string{"class": strings.TrimSpace(st.size + " " + st.weight + " " + st.tracking)}},
		}
	}
	baseDoc := map[string]any{
		"$schema":      dtcgFormatSchema,
		"$description": "Menata App spacing, radius and type tokens, " + who + " (the same in both modes). Generated by ExportDesignTokens; do not edit.",
		"spacing":      spacing, "radius": radius, "typography": typography,
	}
	resolver := map[string]any{
		"$schema":     dtcgResolverSchema,
		"name":        "Menata App, " + who,
		"version":     "2025.10",
		"description": "The base set, then the colour mode: light by default, dark under prefers-color-scheme: dark.",
		"sets":        map[string]any{"base": map[string]any{"sources": []any{map[string]string{"$ref": DesignTokensBaseFile}}}},
		"modifiers": map[string]any{"mode": map[string]any{
			"contexts": map[string]any{
				"light": []any{map[string]string{"$ref": DesignTokensLightFile}},
				"dark":  []any{map[string]string{"$ref": DesignTokensDarkFile}},
			},
			"default": "light",
		}},
		"resolutionOrder": []any{map[string]string{"$ref": "#/sets/base"}, map[string]string{"$ref": "#/modifiers/mode"}},
	}
	var out DesignTokenFiles
	for _, f := range []struct {
		dst *[]byte
		doc any
	}{{&out.Base, baseDoc}, {&out.Light, lightDoc}, {&out.Dark, darkDoc}, {&out.Resolver, resolver}} {
		var buf bytes.Buffer
		enc := json.NewEncoder(&buf)
		enc.SetEscapeHTML(false)
		enc.SetIndent("", "  ")
		if err := enc.Encode(f.doc); err != nil {
			return DesignTokenFiles{}, err
		}
		*f.dst = buf.Bytes()
	}
	return out, nil
}

// appCSSDarkMedia opens app.css's compiled dark block (input.css's, minified).
const appCSSDarkMedia = "@media (prefers-color-scheme:dark){:root{"

var cssCustomProperty = regexp.MustCompile(`(--[a-z0-9-]+):([^;}]+)`)

// appCSSModeVars reads app.css's custom properties as each mode resolves them: the first declaration of each outside the
// dark block, and the dark block over those.
func appCSSModeVars(css string) (light, dark map[string]string, err error) {
	before, rest, ok := strings.Cut(css, appCSSDarkMedia)
	if !ok {
		return nil, nil, fmt.Errorf("app.css has no %q -- the dark block moved or was not compiled", appCSSDarkMedia)
	}
	block, after, ok := strings.Cut(rest, "}}")
	if !ok {
		return nil, nil, fmt.Errorf("app.css's dark block does not close")
	}
	light = map[string]string{}
	for _, m := range cssCustomProperty.FindAllStringSubmatch(before+after, -1) {
		if _, seen := light[m[1]]; !seen {
			light[m[1]] = strings.TrimSpace(m[2])
		}
	}
	dark = map[string]string{}
	for k, v := range light {
		dark[k] = v
	}
	for _, m := range cssCustomProperty.FindAllStringSubmatch(block, -1) {
		dark[m[1]] = strings.TrimSpace(m[2])
	}
	return light, dark, nil
}

// themeOverrideBlock is the declarations of one of themeCSS's two media blocks.
func themeOverrideBlock(css, media string) map[string]string {
	out := map[string]string{}
	_, rest, ok := strings.Cut(css, media+"{:root{")
	if !ok {
		return out
	}
	body, _, _ := strings.Cut(rest, "}}")
	for _, d := range strings.Split(body, ";") {
		if k, v, ok := strings.Cut(d, ":"); ok {
			out[k] = v
		}
	}
	return out
}

// cssColour is a colour as OKLCH, with the sRGB hex it was written as, when it was written as one.
type cssColour struct {
	L, C, H float64
	hex     string
}

// dtcg is the DTCG 2025.10 colour value (Color Module §4): oklch components as the CSS wrote them, or sRGB for a colour
// written in hex, each with its 6-digit hex fallback (gamut-clipped for an oklch outside sRGB).
func (c cssColour) dtcg() map[string]any {
	if c.hex != "" {
		r, g, b := hexRGB(c.hex)
		return map[string]any{"colorSpace": "srgb", "components": []float64{round(r, 4), round(g, 4), round(b, 4)}, "hex": c.hex}
	}
	r, g, b := oklchToSRGB(c.L, c.C, c.H)
	return map[string]any{"colorSpace": "oklch", "components": []float64{c.L, c.C, c.H}, "hex": rgbHex(r, g, b)}
}

var (
	oklchValue   = regexp.MustCompile(`^oklch\(([0-9.]+)% ([0-9.]+) ([0-9.]+)\)$`)
	hexValue     = regexp.MustCompile(`^#(?:[0-9a-f]{3}|[0-9a-f]{6})$`)
	varValue     = regexp.MustCompile(`^var\((--[a-z0-9-]+)\)$`)
	oklabMixArgs = regexp.MustCompile(`^color-mix\(in oklab,\s*(.+?),\s*(.+?)\s+([0-9.]+)%\)$`)
)

// resolveCSSColour follows a custom property to the colour it draws: through `var()` aliases, and through the one
// `color-mix` form themeCSS writes (`color-mix(in oklab, <colour>, <colour> <p>%)`, the free accent's hover).
func resolveCSSColour(vars map[string]string, prop string) (cssColour, error) {
	v, ok := vars[prop]
	if !ok {
		return cssColour{}, fmt.Errorf("%s is not declared", prop)
	}
	return parseCSSColour(vars, v, 0)
}

func parseCSSColour(vars map[string]string, v string, depth int) (cssColour, error) {
	if depth > 8 {
		return cssColour{}, fmt.Errorf("%q: alias chain too deep", v)
	}
	v = strings.TrimSpace(v)
	switch {
	case v == "black":
		return cssColour{hex: "#000000"}, nil
	case v == "white":
		return cssColour{L: 1, hex: "#ffffff"}, nil
	case varValue.MatchString(v):
		next := varValue.FindStringSubmatch(v)[1]
		nv, ok := vars[next]
		if !ok {
			return cssColour{}, fmt.Errorf("%s is not declared", next)
		}
		return parseCSSColour(vars, nv, depth+1)
	case oklchValue.MatchString(v):
		m := oklchValue.FindStringSubmatch(v)
		l, _ := strconv.ParseFloat(m[1], 64)
		c, _ := strconv.ParseFloat(m[2], 64)
		h, _ := strconv.ParseFloat(m[3], 64)
		return cssColour{L: round(l/100, 6), C: c, H: h}, nil
	case hexValue.MatchString(v):
		hex := v
		if len(hex) == 4 {
			hex = "#" + strings.Repeat(hex[1:2], 2) + strings.Repeat(hex[2:3], 2) + strings.Repeat(hex[3:4], 2)
		}
		r, g, b := hexRGB(hex)
		l, c, h := srgbToOKLCH(r, g, b)
		return cssColour{L: l, C: c, H: h, hex: hex}, nil
	case oklabMixArgs.MatchString(v):
		m := oklabMixArgs.FindStringSubmatch(v)
		a, err := parseCSSColour(vars, m[1], depth+1)
		if err != nil {
			return cssColour{}, err
		}
		b, err := parseCSSColour(vars, m[2], depth+1)
		if err != nil {
			return cssColour{}, err
		}
		p, _ := strconv.ParseFloat(m[3], 64)
		return mixOKLab(a, b, p/100), nil
	}
	return cssColour{}, fmt.Errorf("%q is not a colour this exporter can read", v)
}

// mixOKLab is CSS `color-mix(in oklab, a, b p)`: a weighted (1-p, p) in OKLab, written back as OKLCH.
func mixOKLab(a, b cssColour, p float64) cssColour {
	la, aa, ba := oklchToOKLab(a.L, a.C, a.H)
	lb, ab, bb := oklchToOKLab(b.L, b.C, b.H)
	l, x, y := la*(1-p)+lb*p, aa*(1-p)+ab*p, ba*(1-p)+bb*p
	c := math.Hypot(x, y)
	h := math.Mod(math.Atan2(y, x)*180/math.Pi+360, 360)
	if c < 1e-6 {
		c, h = 0, 0
	}
	return cssColour{L: round(l, 4), C: round(c, 4), H: round(h, 3)}
}

func oklchToOKLab(l, c, h float64) (float64, float64, float64) {
	return l, c * math.Cos(h*math.Pi/180), c * math.Sin(h*math.Pi/180)
}

// oklchToSRGB converts to gamma-encoded sRGB, each channel clipped to [0, 1] (Björn Ottosson's OKLab matrices).
func oklchToSRGB(L, C, H float64) (float64, float64, float64) {
	_, a, b := oklchToOKLab(L, C, H)
	l := math.Pow(L+0.3963377774*a+0.2158037573*b, 3)
	m := math.Pow(L-0.1055613458*a-0.0638541728*b, 3)
	s := math.Pow(L-0.0894841775*a-1.2914855480*b, 3)
	enc := func(v float64) float64 {
		v = math.Min(1, math.Max(0, v))
		if v <= 0.0031308 {
			return 12.92 * v
		}
		return 1.055*math.Pow(v, 1/2.4) - 0.055
	}
	return enc(4.0767416621*l - 3.3077115913*m + 0.2309699292*s),
		enc(-1.2684380046*l + 2.6097574011*m - 0.3413193965*s),
		enc(-0.0041960863*l - 0.7034186147*m + 1.7076147010*s)
}

func srgbToOKLCH(r, g, b float64) (float64, float64, float64) {
	dec := func(v float64) float64 {
		if v <= 0.04045 {
			return v / 12.92
		}
		return math.Pow((v+0.055)/1.055, 2.4)
	}
	r, g, b = dec(r), dec(g), dec(b)
	l := math.Cbrt(0.4122214708*r + 0.5363325363*g + 0.0514459929*b)
	m := math.Cbrt(0.2119034982*r + 0.6806995451*g + 0.1073969566*b)
	s := math.Cbrt(0.0883024619*r + 0.2817188376*g + 0.6299787005*b)
	L := 0.2104542553*l + 0.7936177850*m - 0.0040720468*s
	A := 1.9779984951*l - 2.4285922050*m + 0.4505937099*s
	B := 0.0259040371*l + 0.7827717662*m - 0.8086757660*s
	c := math.Hypot(A, B)
	h := math.Mod(math.Atan2(B, A)*180/math.Pi+360, 360)
	if c < 1e-4 {
		c, h = 0, 0
	}
	return round(L, 4), round(c, 4), round(h, 3)
}

func hexRGB(hex string) (float64, float64, float64) {
	n, _ := strconv.ParseUint(hex[1:], 16, 32)
	return float64(n>>16&0xff) / 255, float64(n>>8&0xff) / 255, float64(n&0xff) / 255
}

func rgbHex(r, g, b float64) string {
	return fmt.Sprintf("#%02x%02x%02x", int(math.Round(r*255)), int(math.Round(g*255)), int(math.Round(b*255)))
}

// cssLengthPx turns a spacing, height or radius utility into px, from app.css's own `--spacing` and `--radius-*`.
// `rounded-full` is Tailwind's infinite radius, written as the artifact writes it, 9999px.
func cssLengthPx(vars map[string]string, class string) (float64, error) {
	if step, ok := strings.CutPrefix(class, "rounded-"); ok {
		if step == "full" {
			return 9999, nil
		}
		return remPx(vars["--radius-"+step])
	}
	n, err := strconv.ParseFloat(class[strings.LastIndex(class, "-")+1:], 64)
	if err != nil {
		return 0, fmt.Errorf("%s is not a spacing step", class)
	}
	unit, err := remPx(vars["--spacing"])
	if err != nil {
		return 0, err
	}
	return round(n*unit, 4), nil
}

var cssLineHeightRatio = regexp.MustCompile(`^calc\(([0-9.]+) / ([0-9.]+)\)$`)

// cssTextPx is a text utility's size and line height in px.
func cssTextPx(vars map[string]string, class string) (size, lineHeight float64, err error) {
	size, err = remPx(vars["--"+class])
	if err != nil {
		return 0, 0, fmt.Errorf("%s: %w", class, err)
	}
	lh := vars["--"+class+"--line-height"]
	if m := cssLineHeightRatio.FindStringSubmatch(lh); m != nil {
		a, _ := strconv.ParseFloat(m[1], 64)
		b, _ := strconv.ParseFloat(m[2], 64)
		return size, round(a/b*size, 4), nil
	}
	r, err := strconv.ParseFloat(lh, 64)
	if err != nil {
		return 0, 0, fmt.Errorf("%s: line height %q", class, lh)
	}
	return size, round(r*size, 4), nil
}

func remPx(v string) (float64, error) {
	n, ok := strings.CutSuffix(v, "rem")
	f, err := strconv.ParseFloat(n, 64)
	if !ok || err != nil {
		return 0, fmt.Errorf("expected a rem value, got %q", v)
	}
	return round(f*16, 4), nil
}

// cssFontFamily splits a CSS font-family list into DTCG's array of names.
func cssFontFamily(v string) ([]string, error) {
	var out []string
	for _, f := range strings.Split(v, ",") {
		if f = strings.Trim(strings.TrimSpace(f), `"'`); f != "" {
			out = append(out, f)
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("app.css declares no --font-sans")
	}
	return out, nil
}

func dtcgPx(px float64) map[string]any { return map[string]any{"value": px, "unit": "px"} }

func round(f float64, places int) float64 {
	p := math.Pow(10, float64(places))
	return math.Round(f*p) / p
}

func sortedNames[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	slices.Sort(out)
	return out
}
